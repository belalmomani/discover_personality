int _digitSum(int n) {
  var s = 0;
  for (final c in n.toString().split('')) {
    s += int.parse(c);
  }
  return s;
}

/// Numerology "life path number": sum all digits of day+month+year and reduce to 1..9,
/// keeping the master numbers 11, 22 and 33. Example: 19/12/1985 -> 36 -> 9.
int lifePathNumber(DateTime d) {
  var n = _digitSum(int.parse('${d.day}${d.month}${d.year}'));
  while (n > 9 && n != 11 && n != 22 && n != 33) {
    n = _digitSum(n);
  }
  return n;
}

