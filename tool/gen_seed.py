# Generates supabase/seed.sql from assets/data/questions_ar.json (questions table only; no user data)
import json
d = json.load(open("assets/data/questions_ar.json", encoding="utf-8"))
esc = lambda s: s.replace("'", "''")
rows = []
for q in d["questions"]:
    rows.append("  (%d, '%s', '%s', '%s', %s, '%s', %d)" % (q["id"], q["system"], q["dimension"], esc(q["topic"]), "true" if q["reverse"] else "false", esc(q["text"]), q["id"]))
sql = "-- Generated by tool/gen_seed.py. Safe to re-run.\ninsert into public.questions (id, system, dimension, topic, reverse, text_ar, sort_order) values\n" + ",\n".join(rows) + "\non conflict (id) do update set system=excluded.system, dimension=excluded.dimension, topic=excluded.topic, reverse=excluded.reverse, text_ar=excluded.text_ar, sort_order=excluded.sort_order;\n"
open("supabase/seed.sql", "w", encoding="utf-8").write(sql)
print("ok")
