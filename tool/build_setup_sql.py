#!/usr/bin/env python3
"""Builds supabase/setup_all.sql = every migration + seed, in the correct order (all idempotent)."""
import os

ORDER = [
    "supabase/migrations/20260101000000_init.sql",
    "supabase/seed.sql",
    "supabase/migrations/20260102000000_social.sql",
    "supabase/migrations/20260103000000_similarity_v2.sql",
    "supabase/migrations/20260104000000_chat_images.sql",
    "supabase/migrations/20260105000000_similarity_cache.sql",
    "supabase/migrations/20260106000000_catalog_v2.sql",
]

parts = [
    "-- =====================================================================\n"
    "-- SETUP ALL: runs every migration + seed in order. Safe to re-run (idempotent).\n"
    "-- Paste into Supabase SQL Editor and press Run. Generated by tool/build_setup_sql.py\n"
    "-- DO NOT edit by hand: edit the individual files and rebuild.\n"
    "-- ====================================================================="
]
for p in ORDER:
    body = open(p, encoding="utf-8").read().rstrip() + "\n"
    parts.append(f"\n\n-- ############ BEGIN {os.path.basename(p)} ############\n{body}-- ############ END {os.path.basename(p)} ############\n")
open("supabase/setup_all.sql", "w", encoding="utf-8").write("".join(parts))
print("ok", sum(len(x) for x in parts), "chars")
